function buildDeck(items: string[], prefix: string, colorFor: (i: number) => string): CardItem[] {
  return items.map((title, i) => ({ id: `${prefix}-${i}`, title, color: colorFor(i) }));
}

export function deckForStage(kind: StageKind): CardItem[] {
  if (kind === 'values') return buildDeck(VALUES, 'value', (i) => VALUE_PALETTE[i % VALUE_PALETTE.length]);
  if (kind === 'questions') return buildDeck(QUESTIONS, 'question', () => QUESTION_COLOR);
  return buildDeck(MISSIONS, 'mission', () => MISSION_COLOR);
}
